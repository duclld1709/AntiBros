"""``antibros stats``: corpus statistics -> ``reports/corpus_stats.md``.

Every number comes from ``data/processed`` (documents, chunks, timings) or the manifest
verification log; nothing is estimated here.
"""

from __future__ import annotations

import statistics
from collections import Counter
from pathlib import Path
from typing import Any

from antibros.chunking.base import Chunk
from antibros.config import AppConfig
from antibros.ingestion.evidence import EVIDENCE_LABELS
from antibros.ingestion.pipeline import load_documents
from antibros.ingestion.schemas import CLEANING_VERSION, STANDARD_SECTIONS, Document
from antibros.io import is_valid_windows_filename, read_json, write_text

MIN_STANDARD_SECTIONS = 3


def invalid_filenames(root: Path) -> list[Path]:
    """Paths under ``root`` whose name is not a valid Windows file name."""
    if not root.exists():
        return []
    return [p for p in sorted(root.rglob("*")) if not is_valid_windows_filename(p.name)]


def _percentile(values: list[int], q: float) -> int:
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, round(q * (len(ordered) - 1)))]


def _table(header: list[str], rows: list[list[Any]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def render(
    docs: list[Document],
    chunks: dict[str, list[Chunk]],
    timings: dict[str, Any],
    verification: list[dict[str, Any]],
    bad_files: list[Path],
    chunk_size: int,
) -> str:
    out = [
        "# Corpus statistics (M1)",
        "",
        "Generated by `antibros stats` from `data/processed/`. "
        f"Cleaning version: `{CLEANING_VERSION}`.",
        "",
        "## Manifest verification (Europe PMC REST API)",
    ]
    if verification:
        rows = [
            [v["doc_id"], "pass" if v["ok"] else "**fail**", "; ".join(v["reasons"]) or "-"]
            for v in verification
        ]
        out += [_table(["PMCID", "Result", "Reasons"], rows)]
        failed = [v for v in verification if not v["ok"]]
        out += [
            "",
            f"{len(verification) - len(failed)}/{len(verification)} candidates passed "
            "(isOpenAccess = Y, full text in Europe PMC, CC licence, expected year)."
            + (
                " Rejected candidates were replaced by fallbacks."
                if failed
                else " No replacements."
            ),
        ]
    else:
        out += ["Verification log not found (run `antibros manifest`)."]

    out += ["", "## Documents", ""]
    rows = []
    for d in docs:
        std = sorted(d.standard_sections(), key=STANDARD_SECTIONS.index)
        rows.append(
            [
                d.doc_id,
                d.topic,
                d.year,
                f"{d.evidence_level} ({EVIDENCE_LABELS[d.evidence_level]})",
                d.license,
                f"{len(d.clean_text):,}",
                ", ".join(std),
            ]
        )
    out += [
        _table(
            [
                "PMCID",
                "Topic",
                "Year",
                "Evidence level",
                "License",
                "Clean chars",
                "Standard sections",
            ],
            rows,
        )
    ]

    by_topic = Counter(d.topic for d in docs)
    by_level = Counter((d.topic, d.evidence_level) for d in docs)
    levels = sorted({d.evidence_level for d in docs})
    out += ["", "## Documents by topic and evidence level", ""]
    out += [
        _table(
            ["Topic", *(f"L{lv}" for lv in levels), "Total"],
            [[t, *(by_level[(t, lv)] for lv in levels), by_topic[t]] for t in sorted(by_topic)]
            + [["All", *(sum(by_level[(t, lv)] for t in by_topic) for lv in levels), len(docs)]],
        )
    ]
    detected = sum(len(d.standard_sections()) >= MIN_STANDARD_SECTIONS for d in docs)
    out += [
        "",
        f"Section detection: **{detected}/{len(docs)}** documents have at least "
        f"{MIN_STANDARD_SECTIONS} standard sections ({', '.join(STANDARD_SECTIONS)}).",
    ]

    out += ["", f"## Chunks per strategy (tokens: embedding tokenizer; target {chunk_size})", ""]
    rows = []
    for name, cs in chunks.items():
        toks = [c.token_count for c in cs]
        if not toks:
            continue
        rows.append(
            [
                name,
                len(cs),
                min(toks),
                _percentile(toks, 0.1),
                _percentile(toks, 0.5),
                _percentile(toks, 0.9),
                max(toks),
                f"{statistics.mean(toks):.0f}",
                sum(t > chunk_size for t in toks),
            ]
        )
    out += [
        _table(
            ["Strategy", "Chunks", "Min", "P10", "Median", "P90", "Max", "Mean", f"> {chunk_size}"],
            rows,
        )
    ]

    out += ["", "## Index and timing", ""]
    index = timings.get("index", {})
    colls: dict[str, dict[str, float]] = index.get("collections", {})
    if colls:
        out += [
            _table(
                ["Collection", "Points", "Model load (s)", "Embed (s)", "Upsert (s)"],
                [
                    [n, int(v["points"]), v["model_load_s"], v["embed_s"], v["upsert_s"]]
                    for n, v in sorted(colls.items())
                ],
            )
        ]
    ingest_s = timings.get("ingest", {}).get("seconds")
    index_s = index.get("last_run_s")
    out += [
        "",
        f"- Ingest (fetch/cache, parse, clean): {'TBD' if ingest_s is None else ingest_s} s",
        f"- Index (chunk all strategies + embed + upsert, last full run): "
        f"{index_s if index_s is not None else 'TBD'} s",
    ]
    if ingest_s is not None and index_s is not None:
        total = ingest_s + index_s
        verdict = "within" if total <= 600 else "**over**"
        out += [f"- Total: {total:.1f} s ({verdict} the 10-minute budget)"]
    out += [
        "",
        "## File names under `data/`",
        "",
        "All valid on Windows."
        if not bad_files
        else "Invalid names: " + ", ".join(f"`{p}`" for p in bad_files),
        "",
    ]
    return "\n".join(out)


def write_stats(cfg: AppConfig) -> Path:
    from antibros.indexing.pipeline import chunks_path, read_chunks

    processed = cfg.ingestion.processed_dir
    docs = load_documents(processed)
    chunks: dict[str, list[Chunk]] = {
        name: read_chunks(chunks_path(processed, name))
        for name in cfg.index.chunkers
        if chunks_path(processed, name).exists()
    }
    timings_path = processed / "timings.json"
    timings = read_json(timings_path) if timings_path.exists() else {}
    ver_path = cfg.reports_dir / "corpus_verification.json"
    verification = read_json(ver_path) if ver_path.exists() else []
    data_root = processed.parent
    text = render(
        docs, chunks, timings, verification, invalid_filenames(data_root), cfg.chunking.chunk_size
    )
    out = cfg.reports_dir / "corpus_stats.md"
    write_text(out, text)
    return out
